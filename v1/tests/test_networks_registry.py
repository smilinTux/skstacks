"""v1/ansible/shared/networks must match the deploy playbooks.

The registry is generated by v1/scripts/networks_registry.py from every
playbook's default app_networks, so people can eyeball the subnet map and
pick a free /24. It is only useful if it is current: a service added without
regenerating it would make its subnet look free to the next author.
"""
import pathlib
import subprocess
import sys

V1 = pathlib.Path(__file__).resolve().parents[1]


def test_networks_registry_is_current():
    r = subprocess.run(
        [sys.executable, str(V1 / "scripts" / "networks_registry.py"), "--check"],
        capture_output=True, text=True,
    )
    assert r.returncode == 0, r.stderr
