#!/usr/bin/env python3
"""Turn the latest skpatch-images run into a PR, and queue green ones.

Run by a timer on the ops host (it needs a gh login that may open PRs on
smilinTux/skstacks; PRs opened with the workflow's own GITHUB_TOKEN would
not trigger CI). Two steps, both idempotent:

  1. open: download the newest successful `skpatch-patched-images` artifact
     from main, render v1/ansible/shared/vars/skpatch_patched_images.yml, and
     when it differs from main open a PR from a new branch
     skpatch/patched-images-<run id>. Older open skpatch PRs are closed as
     superseded. Nothing is force-pushed.
  2. queue: every open skpatch PR whose checks are all green is added to the
     merge queue (security fixes merge themselves when green, the shared
     Renovate policy).

  update_overrides.py --repo-dir ~/clawd/skcapstone-repos/skstacks [--dry-run]
"""
import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

GH_REPO = "smilinTux/skstacks"
VARS = "v1/ansible/shared/vars/skpatch_patched_images.yml"
PREFIX = "skpatch/patched-images-"
HEADER = """# GENERATED by tools/skpatch_images/update_overrides.py from the output of
# .github/workflows/skpatch-images.yml. Do not edit by hand: the next run
# rewrites it. To stop one image being swapped, add its repository to
# skstacks_patched_images_skip in the estate's group_vars instead.
#
# Each key is an upstream image reference exactly as a template pins it.
# The value is the same image with its fixable OS-package CVEs patched by
# Copacetic, pushed as a tag of ghcr.io/smilintux/skpatched and pinned by digest.
# shared/tasks/skpatch_image_overrides.yml swaps them into the rendered stack
# file before the pre-pull, so nothing changes until a deploy runs.
---
"""


def sh(*args, cwd=None, check=True):
    return subprocess.run(args, cwd=cwd, check=check, capture_output=True, text=True).stdout


def gh_json(*args):
    return json.loads(sh("gh", *args) or "null")


def render(mapping):
    if not mapping:
        return HEADER + "skpatch_patched_images: {}\n"
    lines = [HEADER + "skpatch_patched_images:"]
    for ref in sorted(mapping):
        e = mapping[ref]
        b, a = e["before"], e["after"]
        lines.append(f'  "{ref}":')
        lines.append(f'    image: "{e["image"]}"')
        lines.append(f'    # critical/high fixable: {b["critical"]}/{b["high"]} upstream, {a["critical"]}/{a["high"]} patched')
    return "\n".join(lines) + "\n"


def latest_run():
    runs = gh_json("run", "list", "-R", GH_REPO, "-w", "skpatch-images.yml", "-b", "main",
                   "-s", "success", "-L", "1", "--json", "databaseId,createdAt")
    return runs[0] if runs else None


def open_prs():
    prs = gh_json("pr", "list", "-R", GH_REPO, "--state", "open", "--limit", "50",
                  "--json", "number,headRefName,statusCheckRollup,mergeable,isDraft")
    return [p for p in prs if p["headRefName"].startswith(PREFIX)]


def step_open(repo_dir, dry):
    run = latest_run()
    if not run:
        print("no successful skpatch-images run on main yet")
        return
    rid = run["databaseId"]
    if any(p["headRefName"] == f"{PREFIX}{rid}" for p in open_prs()):
        print(f"run {rid}: PR already open")
        return
    with tempfile.TemporaryDirectory() as td:
        sh("gh", "run", "download", str(rid), "-R", GH_REPO, "-n", "skpatch-patched-images", "-D", td)
        mapping = json.loads((Path(td) / "skpatch-patched-images.json").read_text())
    sh("git", "fetch", "-q", "origin", "main", cwd=repo_dir)
    current = sh("git", "show", f"origin/main:{VARS}", cwd=repo_dir)
    new = render(mapping)
    if new == current:
        print(f"run {rid}: mapping unchanged ({len(mapping)} images)")
        return
    branch = f"{PREFIX}{rid}"
    if dry:
        print(f"would open {branch} with {len(mapping)} images")
        return
    sh("wt", "switch", "-c", branch, "--base", "origin/main", "--no-cd", "--no-hooks", cwd=repo_dir)
    wt_dir = worktree_of(repo_dir, branch)
    try:
        (wt_dir / VARS).write_text(new)
        sh("git", "add", VARS, cwd=wt_dir)
        sh("git", "commit", "-q", "-m", f"chore(skpatch): patched images from run {rid}\n\n"
           f"{len(mapping)} images with OS-package CVE fixes (Copacetic). Generated by\n"
           "tools/skpatch_images/update_overrides.py.", cwd=wt_dir)
        sh("git", "push", "-q", "-u", "origin", branch, cwd=wt_dir)
        rows = "\n".join(f'| `{r.split("@")[0]}` | {e["before"]["critical"]}/{e["before"]["high"]} | '
                         f'{e["after"]["critical"]}/{e["after"]["high"]} |' for r, e in sorted(mapping.items()))
        body = (f"Generated from skpatch-images run {rid} "
                f"(https://github.com/{GH_REPO}/actions/runs/{rid}).\n\n"
                "Each image below is the pinned upstream image with its fixable OS-package HIGH/CRITICAL "
                "CVEs patched by Copacetic, same run config (checked), pushed to ghcr.io/smilintux/skpatched "
                "and pinned by digest. It takes effect at the next deploy of a release that contains it.\n\n"
                "| upstream | fixable C/H before | after |\n|---|---|---|\n" + rows +
                "\n\nThis PR queues itself once every check is green (security fix, shared Renovate policy).")
        url = sh("gh", "pr", "create", "-R", GH_REPO, "--head", branch, "--base", "main",
                 "--title", f"chore(skpatch): patched images ({len(mapping)}) from run {rid}",
                 "--body", body, "--label", "security", "--label", "dependencies").strip()
        print("opened", url)
        for p in open_prs():
            if p["headRefName"] != branch:
                sh("gh", "pr", "close", str(p["number"]), "-R", GH_REPO, "--delete-branch",
                   "--comment", f"Superseded by {url}.", check=False)
    finally:
        sh("wt", "remove", branch, "--no-delete-branch", cwd=repo_dir, check=False)


def worktree_of(repo_dir, branch):
    path = None
    for line in sh("git", "worktree", "list", "--porcelain", cwd=repo_dir).splitlines():
        if line.startswith("worktree "):
            path = line.split(" ", 1)[1]
        elif line == f"branch refs/heads/{branch}":
            return Path(path)
    raise SystemExit(f"no worktree for {branch}")


def green(pr):
    checks = pr.get("statusCheckRollup") or []
    if not checks or pr.get("isDraft") or pr.get("mergeable") != "MERGEABLE":
        return False
    for c in checks:
        state = (c.get("conclusion") or c.get("state") or "").upper()
        if state not in ("SUCCESS", "SKIPPED", "NEUTRAL"):
            return False
    return True


def step_queue(dry):
    for p in open_prs():
        if not green(p):
            print(f"#{p['number']}: not green yet")
            continue
        if dry:
            print(f"would queue #{p['number']}")
            continue
        node = gh_json("pr", "view", str(p["number"]), "-R", GH_REPO, "--json", "id")["id"]
        out = subprocess.run(["gh", "api", "graphql", "-f",
                              "query=mutation($id:ID!){enqueuePullRequest(input:{pullRequestId:$id}){mergeQueueEntry{position}}}",
                              "-f", f"id={node}"], capture_output=True, text=True)
        print(f"#{p['number']}: queued" if out.returncode == 0 else f"#{p['number']}: queue failed: {out.stderr.strip()[:200]}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-dir", required=True)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    step_open(a.repo_dir, a.dry_run)
    step_queue(a.dry_run)


if __name__ == "__main__":
    sys.exit(main())
